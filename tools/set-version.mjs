#!/usr/bin/env node
/**
 * Writes a release version into every place that carries one, so the git tag
 * and the built app can never disagree.
 *
 * Usage: node tools/set-version.mjs 1.4.0
 *        node tools/set-version.mjs v1.4.0   (leading "v" is stripped)
 *
 * Touches:
 * - package.json                version
 * - android/app/build.gradle    versionName + versionCode (when the platform exists)
 * - src/app-version.ts          compile-time constant for the UI
 */

import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');

const fail = (message) => {
  console.error(`set-version: ${message}`);
  process.exit(1);
};

const raw = process.argv[2];
if (!raw) fail('missing version argument (e.g. node tools/set-version.mjs 1.4.0)');

const version = raw.trim().replace(/^v/, '');
if (!/^\d+\.\d+\.\d+$/.test(version)) {
  fail(`"${raw}" is not a semver version (expected MAJOR.MINOR.PATCH)`);
}

const [major, minor, patch] = version.split('.').map(Number);
if ([minor, patch].some((part) => part > 99)) {
  fail('minor and patch must be 0-99 so they fit the Android versionCode scheme');
}

/** Android caps versionCode growth per major/minor/patch. */
const versionCode = major * 10000 + minor * 100 + patch;

const writeJson = (path, mutate) => {
  const absolute = join(ROOT, path);
  const json = JSON.parse(readFileSync(absolute, 'utf8'));
  mutate(json);
  writeFileSync(absolute, `${JSON.stringify(json, null, 2)}\n`, 'utf8');
  console.log(`  ${path} -> ${version}`);
};

writeJson('package.json', (json) => {
  json.version = version;
});

const gradlePath = join(ROOT, 'android', 'app', 'build.gradle');
if (existsSync(gradlePath)) {
  let gradle = readFileSync(gradlePath, 'utf8');
  const before = gradle;

  if (/versionCode\s+\d+/.test(gradle)) {
    gradle = gradle.replace(/versionCode\s+\d+/, `versionCode ${versionCode}`);
  } else {
    fail('android/app/build.gradle has no versionCode line inside defaultConfig');
  }

  if (/versionName\s+"[^"]*"/.test(gradle)) {
    gradle = gradle.replace(/versionName\s+"[^"]*"/, `versionName "${version}"`);
  } else {
    fail('android/app/build.gradle has no versionName line inside defaultConfig');
  }

  if (gradle !== before) {
    writeFileSync(gradlePath, gradle, 'utf8');
    console.log(`  android/app/build.gradle -> ${version} (versionCode ${versionCode})`);
  }
} else {
  console.log('  android/app/build.gradle not present yet — run `npx cap add android` first');
}

writeFileSync(
  join(ROOT, 'src', 'app-version.ts'),
  `// Generated by tools/set-version.mjs — do not edit.\nexport const APP_VERSION = '${version}';\nexport const APP_VERSION_CODE = ${versionCode};\n`,
  'utf8',
);
console.log(`  src/app-version.ts -> ${version} (${versionCode})`);
console.log(`set-version: ${version} (versionCode ${versionCode})`);
